/*
 * 带间隔的同色配对
 * 来源：教练自命题，同色有序配对的条件变式，不是 ADPC 历届原题。
 * 专题：备赛地图第 6 块按类别维护信息，衔接第 10 块 DP 候选加入时机。
 * 今日第三题：在上一道分类最优值模型上，独立处理合法候选的时间限制。
 * 不预填 IO、状态定义、循环或算法。
 *
 * 题意：
 * 有 n 条按顺序排列的记录，第 i 条包含颜色 c[i] 和数值 a[i]、b[i]。
 * 必须选出两个位置 i、j，满足：
 * 1. i<j 且 c[i]=c[j]。
 * 2. j-i>=L。
 * 得分为 a[i]+b[j]，求最大得分。
 * 无合法配对输出 IMPOSSIBLE；有合法配对时，即使最大得分为负也要输出。
 *
 * 距离按原始位置计算，不按某种颜色内部的出现次数计算。
 * L=1 时与上一道同色有序配对的合法条件一致。
 *
 * 输入：第一行 n k L，随后 n 行，每行 c[i] a[i] b[i]。
 * 范围：1 <= n,k <= 200000，1 <= L <= n，1 <= c[i] <= k。
 * -1000000000 <= a[i],b[i] <= 1000000000。
 * 输出：最大得分或 IMPOSSIBLE。
 *
 * 样例 1 输入：
 * 5 2 3
 * 1 3 8
 * 2 10 2
 * 1 7 4
 * 2 -2 9
 * 1 5 -1
 * 输出：
 * 2
 * 说明：合法同色配对为第 1、5 条，得分 3+(-1)=2。
 * 第 2、4 条虽得分更高，但距离 2 不满足 L=3。
 *
 * 样例 2 输入：
 * 3 1 2
 * 1 -5 100
 * 1 1000 1000
 * 1 8 -7
 * 输出：
 * -12
 *
 * 自行写完整程序；自测两个样例及至少两组自己构造的边界反例。
 */
